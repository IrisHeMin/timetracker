async (page) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const base = await page.evaluate(() => location.origin);
  await page.evaluate(() => localStorage.removeItem("dayledger.web.v1"));
  await page.reload();
  const day = await page.evaluate(() => {
    const date = new Date(); date.setDate(date.getDate() - 1);
    return DayLedger.dayKey(date);
  });
  await page.locator("#day").fill(day);
  await page.locator("#day").dispatchEvent("change");
  await page.locator("#add-task").click();
  await page.locator("#task-name").fill("Browser smoke task");
  await page.locator("#task-category").selectOption("＋ 添加分类…");
  await page.locator("#category-name").fill("自定义测试");
  await page.getByRole("button", {name: "保存分类", exact: true}).click();
  if (await page.locator("#task-category").inputValue() !== "自定义测试") throw Error("New category not selected");
  await page.locator("#task-start").fill("09:00");
  await page.locator("#task-stop").fill("10:00");
  await page.getByRole("button", {name: "保存任务", exact: true}).click();
  await page.locator("#add-task").click();
  await page.locator("#task-name").fill("Overlap task");
  await page.locator("#task-category").selectOption("学习");
  await page.locator("#task-start").fill("09:30");
  await page.locator("#task-stop").fill("10:30");
  await page.getByRole("button", {name: "保存任务", exact: true}).click();
  if (await page.locator("#covered").innerText() !== "1 小时 30 分") throw Error("Incorrect covered time");
  if (await page.locator("#overlap").innerText() !== "30 分钟") throw Error("Incorrect overlap");
  const stop = page.locator("#tasks tr").filter({hasText: "Browser smoke task"}).locator('input[type="time"]').nth(1);
  await stop.fill("11:00"); await stop.dispatchEvent("change");
  if (await page.locator("#covered").innerText() !== "2 小时 0 分") throw Error("Inline time did not save");
  await page.reload();
  await page.locator("#day").fill(day); await page.locator("#day").dispatchEvent("change");
  if (await page.locator("#tasks tr").count() !== 2) throw Error("Tasks did not persist");
  await page.locator("#preview").click();
  if (!await page.locator("#report-content").innerText().then(text => text.includes("自定义测试"))) throw Error("Report missing custom category");
  const downloadEvent = page.waitForEvent("download");
  await page.locator("#save-report").click();
  const download = await downloadEvent;
  const stream = await download.createReadStream();
  stream.setEncoding("utf8");
  let html = "";
  for await (const chunk of stream) html += chunk;
  if (!html.includes("Browser smoke task") || !html.includes("data:image/png;base64,") ||
      !html.includes("--cp-bg")) throw Error("Incomplete downloaded report");
  await page.locator('#report-dialog [data-close]').click();
  await page.locator("#add-task").click();
  await page.locator("#task-name").fill("Invalid interval");
  await page.locator("#task-start").fill("12:00");
  await page.locator("#task-stop").fill("11:00");
  await page.getByRole("button", {name: "保存任务", exact: true}).click();
  if (!await page.locator("#task-error").innerText()) throw Error("Invalid interval accepted");
  await page.locator('#task-dialog [data-close]').click();
  await page.setViewportSize({width: 390, height: 844});
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error("Mobile page overflows");
  await page.screenshot({path: ".playwright-cli\\dayledger-mobile.png", fullPage: true});
  await page.setViewportSize({width: 1440, height: 1000});
  await page.screenshot({path: ".playwright-cli\\dayledger-desktop.png", fullPage: true});
  await page.goto(`${base}/dist/DayLedger-offline.html`);
  const externalScripts = await page.locator("script[src]").count();
  if (externalScripts) throw Error("Offline file has external scripts");
  await page.context().setOffline(true);
  await page.locator("#add-task").click();
  await page.locator("#task-name").fill("Offline smoke task");
  await page.getByRole("button", {name: "保存任务", exact: true}).click();
  if (!await page.locator("#tasks").innerText().then(text => text.includes("Offline smoke task"))) throw Error("Offline task failed");
  await page.context().setOffline(false);
  if (errors.length) throw Error(errors.join("\n"));
  return {result: "passed", covered: "120 minutes", overlap: "60 minutes",
    categoryPersistence: true, reportDownload: true, mobileLayout: true, offline: true};
}
